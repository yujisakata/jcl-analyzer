"""Render specs/ibm-jcl-reference.md from specs/rules.yaml and the Golden suite (ADR-015)."""

from __future__ import annotations

from collections import defaultdict

from jclprof.harness.loader import GoldenCase
from jclprof.harness.registry import RuleRegistry

HEADER = """# IBM JCL Specification Registry

> GENERATED by `uv run jclprof rules-render` from `specs/rules.yaml` and `tests/golden/cases/`.
> Do not edit by hand: edit `specs/rules.yaml` (and the Golden cases), then re-render.
> A harness test fails if this file is out of sync.

Requirements CTX-05, ADR-012, ADR-015. Status values:

- `VERIFIED`: the primary IBM text was opened and read; chapter, section and page are recorded
- `CROSS-CHECKED`: the same content appears in several IBM editions; section and page not recorded
- `PENDING`: primary source not confirmed; dependent checks are INFO only, and cases cannot
  be reviewed or approved
- `PROJECT-POLICY`: not an IBM rule; a project decision about how the tool reports something
  IBM leaves unspecified. Never counted as IBM-backed.

Pages are given as "printed page (PDF page)".
"""


def _cell(s: str) -> str:
    return s.replace("|", "\\|").replace("\n", " ")


def render_reference(registry: RuleRegistry, cases: list[GoldenCase]) -> str:
    by_rule: dict[str, list[str]] = defaultdict(list)
    for c in cases:
        for rid in c.rule_ids:
            by_rule[rid].append(c.test_id)
    L = [HEADER, "## Source documents", "",
         "| Ref | Title | Edition | URL | Retrieved | SHA-256 |", "|---|---|---|---|---|---|"]
    for d in registry.documents.values():
        L.append(f"| {d.id} | {_cell(d.title)} | {_cell(d.edition)} | {d.url} | {d.retrieved} | "
                 f"{d.sha256 or '-'} |")
    counts: dict[str, int] = defaultdict(int)
    for r in registry.rules.values():
        counts[r.status] += 1
    L += ["", "## Status summary", "", "| Status | Rules |", "|---|---|"]
    L += [f"| {k} | {counts[k]} |" for k in sorted(counts)]
    L += ["", "## Rules", "",
          "| Rule ID | Applies to | Summary | Conditions | Source | Edition | Chapter / Section | "
          "Pages | Status | Golden Tests |",
          "|---|---|---|---|---|---|---|---|---|---|"]
    for r in registry.rules.values():
        d = registry.documents[r.doc]
        tests = ", ".join(sorted(by_rule.get(r.id, []))) or "-"
        L.append(f"| {r.id} | {_cell(r.applies_to)} | {_cell(r.summary)} | {_cell(r.conditions)} "
                 f"| {d.url} | {_cell(d.edition)} | {_cell(r.chapter)} > {_cell(r.section)} | "
                 f"{_cell(r.pages)} | {r.status} | {tests} |")
    uncovered = [r.id for r in registry.rules.values() if r.id not in by_rule]
    L += ["", "## Rules without Golden Tests", "",
          ", ".join(uncovered) if uncovered else "None.", ""]
    return "\n".join(L)
