"""Acceptance: inventory of the real CardDemo corpus vs. an independent shell oracle.

Expected values come from ``measure_carddemo.sh`` (find / sha256sum / awk / grep / iconv),
reviewed and committed under ``expected/``. They are never regenerated by this test
(requirements 6.1, 6.2, 9.2, 9.3).
"""

from __future__ import annotations

import collections
from pathlib import Path
from typing import Any

import pytest
import yaml

from conftest import PROJECT_ROOT, snapshot
from jclprof.context.config import load_config
from jclprof.inventory.collector import collect
from jclprof.inventory.model import InventoryResult
from jclprof.inventory.writers import write_outputs

pytestmark = pytest.mark.corpus

EXPECTED_FILE = Path(__file__).parent / "expected" / "carddemo_inventory.yaml"


@pytest.fixture(scope="module")
def expected() -> dict[str, Any]:
    data: dict[str, Any] = yaml.safe_load(EXPECTED_FILE.read_text(encoding="utf-8"))
    return data


@pytest.fixture(scope="module")
def result() -> InventoryResult:
    cfg = load_config(PROJECT_ROOT / "config" / "profiler.yaml")
    if not cfg.roots[0].path.is_dir():
        pytest.skip("CardDemo corpus not available")
    return collect(cfg)


def _ext(rel_path: str) -> str:
    name = rel_path.rsplit("/", 1)[-1]
    if "." not in name or (name.startswith(".") and name.count(".") == 1):
        return ""
    return "." + name.rsplit(".", 1)[-1].lower()


def test_registration_rate_100_percent(result: InventoryResult, expected: dict[str, Any]) -> None:
    assert len(result.source_files) + len(result.excluded) == expected["total_files"]
    assert result.summary()["files_seen"] == expected["total_files"]
    assert sum(s.size_bytes for s in result.source_files) == expected["total_bytes"]


def test_extension_counts(result: InventoryResult, expected: dict[str, Any]) -> None:
    got = collections.Counter(_ext(s.rel_path) for s in result.source_files)
    assert dict(got) == expected["extension_counts"]


def test_asset_type_counts(result: InventoryResult, expected: dict[str, Any]) -> None:
    assert result.summary()["asset_type_counts"] == expected["asset_type_counts"]
    assert "UNKNOWN" not in result.summary()["asset_type_counts"]


def test_encoding_status(result: InventoryResult, expected: dict[str, Any]) -> None:
    # ADR-009 (user decision A1, 2026-11-15): data files use the "data" profile, whose encoding
    # is undetermined -> not decoded. See tests/CHANGES.md (TC-001).
    data_files = sorted(s.rel_path for s in result.source_files if s.asset_type == "DATA")
    undetermined = sorted(
        s.rel_path for s in result.source_files if s.encoding_status == "ENCODING_UNDETERMINED"
    )
    assert undetermined == data_files
    assert len(undetermined) == expected["asset_type_counts"]["DATA"]
    # Oracle: every file that is not valid UTF-8 is a DATA file, so no JCL/PROC/source file
    # fails decoding under its UTF-8 profile.
    assert set(expected["decode_failed_utf8"]) <= set(data_files)
    assert [s.rel_path for s in result.source_files if s.encoding_status == "DECODE_FAILED"] == []
    i004 = sorted(d.rel_path for d in result.diagnostics if d.code == "INV-I004")
    assert i004 == data_files


def test_jcl_family_files(result: InventoryResult, expected: dict[str, Any]) -> None:
    exp: dict[str, Any] = expected["jcl_family_files"]
    got = {s.rel_path: s for s in result.source_files if s.asset_type in ("JCL", "PROC")}
    assert sorted(got) == sorted(exp)
    for rel, e in exp.items():
        s = got[rel]
        assert s.sha256 == e["sha256"], rel
        assert s.physical is not None, rel
        assert s.physical.record_count == e["record_count"], rel
        assert s.physical.max_record_length == e["max_record_length"], rel
        assert s.physical.seq_area_records == e["seq_area_records"], rel
        pc = s.physical.prefix_counts
        for key in ("SLASH_SLASH_STAR", "SLASH_SLASH", "SLASH_STAR", "BLANK"):
            assert pc[key] == e["prefix"][key], (rel, key)
        assert pc["OTHER"] == e["record_count"] - sum(e["prefix"].values()), rel


def test_known_duplicate_and_member_name_findings(result: InventoryResult) -> None:
    dups = {(d.asset_type, d.member_name): d for d in result.duplicate_members}
    assert set(dups) == {("CONTROL_CARDS", "REPROCT")}
    invalid = sorted(
        s.rel_path for s in result.source_files if s.member_name_valid is False
    )
    assert invalid == ["app-transaction-type-db2/ddl/XTRNTYCAT.ddl"]


def test_no_error_diagnostics(result: InventoryResult) -> None:
    assert [d for d in result.diagnostics if d.severity == "ERROR"] == []


def test_corpus_unchanged_by_inventory(corpus_root: Path, tmp_path: Path) -> None:
    before = snapshot(corpus_root)
    cfg = load_config(PROJECT_ROOT / "config" / "profiler.yaml")
    write_outputs(collect(cfg), tmp_path / "out")
    assert snapshot(corpus_root) == before
