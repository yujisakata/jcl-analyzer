#!/usr/bin/env bash
# Independent oracle for the CardDemo inventory acceptance test.
#
# This script measures the corpus using only POSIX/GNU tools (find, sha256sum, awk, grep, iconv),
# never the jclprof code, so its output can serve as an independent expected value
# (requirements 6.1 / 9.3). Its output is reviewed and then committed as
# expected/carddemo_inventory.yaml. The test never regenerates that file automatically.
#
# Usage: bash tests/acceptance/measure_carddemo.sh <corpus-root> > tests/acceptance/expected/carddemo_inventory.yaml
set -euo pipefail
ROOT="${1:?corpus root required}"
cd "$ROOT"

echo "# GENERATED BY tests/acceptance/measure_carddemo.sh (independent shell oracle)."
echo "# Review before committing. Do NOT regenerate to make a failing test pass."
echo "corpus_root: \"$ROOT\""
echo "total_files: $(find . -type f | wc -l)"
echo "total_bytes: $(find . -type f -printf '%s\n' | awk '{s+=$1} END{print s+0}')"

echo "extension_counts:"
find . -type f -printf '%f\n' \
  | awk '{n=$0; if (n ~ /^\.[^.]*$/ || index(n,".")==0) e=""; else {e=n; sub(/.*\./,".",e)}; print tolower(e)}' \
  | sort | uniq -c | awk '{ if (NF==1) printf "  \"\": %d\n", $1; else printf "  \"%s\": %d\n", $2, $1 }'

echo "asset_type_counts:"
echo "  PLACEHOLDER: $(find . -type f -name '.gitkeep' | wc -l)"
echo "  DATA: $(find . -type f -path '*/data/*' ! -name '.gitkeep' | wc -l)"
echo "  CATALOG_LISTING: $(find . -type f -path '*/catlg/*' | wc -l)"
cnt() { find . -type f ! -path '*/data/*' ! -path '*/catlg/*' \( "$@" \) | wc -l; }
echo "  JCL: $(cnt -iname '*.jcl')"
echo "  PROC: $(cnt -iname '*.prc' -o -iname '*.proc')"
echo "  CONTROL_CARDS: $(cnt -iname '*.ctl')"
echo "  COBOL: $(cnt -iname '*.cbl')"
echo "  COPYBOOK: $(cnt -iname '*.cpy')"
echo "  BMS: $(cnt -iname '*.bms')"
echo "  ASSEMBLER: $(cnt -iname '*.asm')"
echo "  MACRO: $(cnt -iname '*.mac')"
echo "  DB2_DDL: $(cnt -iname '*.ddl')"
echo "  DB2_DCLGEN: $(cnt -iname '*.dcl')"
echo "  IMS_PSB: $(cnt -iname '*.psb')"
echo "  IMS_DBD: $(cnt -iname '*.dbd')"
echo "  CICS_CSD: $(cnt -iname '*.csd')"
echo "  SCHEDULER_CA7: $(cnt -iname '*.ca7')"
echo "  SCHEDULER_CONTROLM: $(cnt -iname '*.controlm')"
echo "  DOCUMENT: $(cnt -iname '*.md')"

echo "decode_failed_utf8:"
find . -type f | sort | while read -r f; do
  iconv -f UTF-8 -t UTF-8 "$f" >/dev/null 2>&1 || echo "  - \"${f#./}\""
done

# Per-file facts for JCL-family assets (JCL, PROC).
echo "jcl_family_files:"
find . -type f ! -path '*/data/*' \( -iname '*.jcl' -o -iname '*.prc' -o -iname '*.proc' \) | LC_ALL=C sort | while read -r f; do
  rel="${f#./}"
  sha=$(sha256sum "$f" | awk '{print $1}')
  # record count: awk counts a final record even without a trailing newline
  recs=$(awk 'END{print NR}' "$f")
  ss=$(grep -c '^//\*' "$f" || true)
  s2=$(grep -c '^//' "$f" || true); s2=$((s2-ss))
  st=$(grep -c '^/\*' "$f" || true)
  blank=$(tr -d '\r' < "$f" | grep -c '^ *$' || true)
  # max record length excluding CR/LF
  maxlen=$(tr -d '\r' < "$f" | awk '{ if (length($0)>m) m=length($0) } END{print m+0}')
  # records with non-blank content in columns 73-80
  seq=$(tr -d '\r' < "$f" | awk 'length($0)>72 { s=substr($0,73,8); if (s ~ /[^ ]/) c++ } END{print c+0}')
  echo "  \"$rel\":"
  echo "    sha256: $sha"
  echo "    record_count: $recs"
  echo "    max_record_length: $maxlen"
  echo "    seq_area_records: $seq"
  echo "    prefix: {SLASH_SLASH_STAR: $ss, SLASH_SLASH: $s2, SLASH_STAR: $st, BLANK: $blank}"
done
